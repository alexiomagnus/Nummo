// The sprite sits in a 14×14 canvas: one spare pixel per side for the optional halo.
// Halo = "sticker" ring drawn on every empty pixel touching the sprite (8 neighbours), so the
// dark outline stays visible on dark surfaces without recolouring the sprite.
export function pixelSvg(rows: readonly string[], options: { halo?: string } = {}): string {
  const filled = (x: number, y: number) => Boolean(pixelPalette[rows[y]?.[x] ?? '.']);
  const rects: string[] = [];
  const rect = (x: number, y: number, fill: string) => rects.push(`<rect x="${x + 1}" y="${y + 1}" width="1" height="1" fill="${fill}"/>`);
  if (options.halo) {
    for (let y = -1; y <= pixelSize; y++) {
      for (let x = -1; x <= pixelSize; x++) {
        if (filled(x, y)) continue;
        let touches = false;
        for (let dy = -1; dy <= 1 && !touches; dy++) for (let dx = -1; dx <= 1; dx++) if (filled(x + dx, y + dy)) touches = true;
        if (touches) rect(x, y, options.halo);
      }
    }
  }
  rows.forEach((row, y) => Array.from(row).forEach((char, x) => {
    const fill = pixelPalette[char];
    if (fill) rect(x, y, fill);
  }));
  const canvas = pixelSize + 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${canvas} ${canvas}" shape-rendering="crispEdges">${rects.join('')}</svg>`;
}
