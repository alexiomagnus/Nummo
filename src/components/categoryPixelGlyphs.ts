// Pixel-art category glyphs: the third icon set next to the minimal outlines (categoryGlyphs.ts) and the colourful
// drawings (categoryColorGlyphs.ts). Same IDs, same subject, hue chosen by meaning like the colourful set.
//
// Each icon is a small sprite: rows of characters on a grid of at most 12×12 cells, drawn centred on a 12×12 canvas that
// is shown at 24×24 (two device-independent pixels per cell, so the edges stay sharp at 24, 48… px). Characters:
//   .  empty        i  ink (outline)   b  base      t  tint      o  on-base (details on a base fill)
// They map to the same colour roles as the colourful set ({i} {b} {t} {o}), resolved per theme by categoryIconSets.ts, so
// there are no hex values here. Thin details that touch no fill use b/t, never i: in the dark theme the ink is dark.
// To add an icon: add its ID to categoryIconLabels and categoryGlyphs.ts, then a hue and a sprite here (tests enforce it).
